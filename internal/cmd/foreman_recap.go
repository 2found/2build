// The recap is the human's read of a finished project: one self-contained
// HTML page built from durable state (contract, phases, commits, releases,
// coverage, tickets) plus the Foreman's own report.md narrative. It is a
// rendering, never a record — readiness and completion stay on the JSON.

func projectRecapPath(st *ticket.Store) string { return filepath.Join(st.Home(), "recap.html") }

func writeProjectRecap(st *ticket.Store, s projectSnapshot) (string, error) {
	path := projectRecapPath(st)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(renderProjectRecap(st, s)), 0o644); err != nil {
		return "", err
	}
	return path, os.Rename(tmp, path)
}

func renderProjectRecap(st *ticket.Store, s projectSnapshot) string {
	esc := html.EscapeString
	doc := ticket.ReadDoc(st.IndexPath())
	title := doc.Get("title")
	if title == "" {
		title = s.Ticket
	}
	var b strings.Builder
	b.WriteString(`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">`)
	fmt.Fprintf(&b, "<title>%s handover</title><style>%s</style></head><body><main>", esc(title), recapCSS)
	fmt.Fprintf(&b, "<header><p class=eyebrow>Team handover · %s</p><h1>%s</h1>", esc(s.Ticket), esc(title))
	meta := []string{"Observed " + s.Observed, "Completion: " + orDefault(s.Completion, "not completed")}
	if id := s.Coordinator["id"]; id != "" {
		meta = append(meta, "Team lead "+id)
	}
	fmt.Fprintf(&b, "<p class=meta>%s</p>", esc(strings.Join(meta, " · ")))
	if c := s.Contract; c != nil {
		fmt.Fprintf(&b, "<p class=lead>%s</p><p class=meta>For: %s</p>", esc(c.Outcome), esc(c.Audience))
	}
	b.WriteString("</header>")

	if len(s.Blockers) > 0 {
		b.WriteString(`<section class="card warn"><h2>Open blockers</h2><ul>`)
		for _, x := range s.Blockers {
			fmt.Fprintf(&b, "<li><code>%s</code></li>", esc(x))
		}
		b.WriteString("</ul></section>")
	}

	rows, rowsErr := readDecisionRows(st)
	live, hidden, flags := auditDecisions(st, s, rows)
	if len(flags) > 0 {
		b.WriteString(`<section class="card warn"><h2>Check first</h2><p class=meta>Decisions whose evidence does not resolve or whose result is not verified.</p><ul>`)
		for _, f := range flags {
			fmt.Fprintf(&b, "<li><code>%s</code> %s</li>", esc(f.Row), esc(f.Reason))
		}
		b.WriteString("</ul></section>")
	}

	if body, err := os.ReadFile(filepath.Join(st.Home(), "report.md")); err == nil && strings.TrimSpace(string(body)) != "" {
		fmt.Fprintf(&b, `<section class=card><h2>Handover</h2><div class=md>%s</div></section>`, recapMarkdown(string(body)))
	}

	if rowsErr == nil {
		b.WriteString(`<section class=card><h2>Decisions</h2><div class=scroll><table><tr><th>Row</th><th>Phase</th><th>Decision</th><th>Why</th><th>Evidence</th><th>Result</th></tr>`)
		for _, r := range live {
			fmt.Fprintf(&b, "<tr><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>", esc(r.ID), esc(r.Phase), esc(r.Decision), esc(r.Why), recapInline("`"+r.Evidence+"`"), recapBadge(r.Result))
		}
		b.WriteString("</table></div>")
		if hidden > 0 {
			fmt.Fprintf(&b, "<p class=note>%d superseded row(s) hidden; decisions.jsonl keeps them.</p>", hidden)
		}
		b.WriteString("</section>")
	} else {
		b.WriteString(`<section class=card><h2>Decisions</h2><p class=note>No decision trail: this project wrote no decisions.jsonl.</p></section>`)
	}

	if len(s.Phases) > 0 {
		b.WriteString("<section><h2>Phases</h2>")
		for _, p := range s.Phases {
			recapPhase(&b, p)
		}
		b.WriteString("</section>")
	}

	if len(s.Coverage) > 0 {
		b.WriteString(`<section class=card><h2>Acceptance criteria</h2><div class=scroll><table><tr><th>ID</th><th>Criterion</th><th>State</th><th>Evidence</th></tr>`)
		for _, c := range s.Coverage {
			fmt.Fprintf(&b, "<tr><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td></tr>", esc(c.ID), esc(c.Text), recapBadge(c.State), esc(strings.Join(c.Evidence, ", ")))
		}
		b.WriteString("</table></div></section>")
	}

	if len(s.Children) > 0 {
		b.WriteString(`<section class=card><h2>Tickets</h2><div class=scroll><table><tr><th>Ticket</th><th>Title</th><th>Seed</th><th>State</th><th>Notes</th></tr>`)
		for _, c := range s.Children {
			notes := append([]string{}, c.Problems...)
			if c.Waiver != nil {
				notes = append(notes, "waived "+strings.Join(c.Waiver.Gates, "+")+": "+c.Waiver.Reason)
			}
			fmt.Fprintf(&b, "<tr><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>", esc(c.ID), esc(c.Title), esc(c.Seed), recapBadge(c.State), esc(strings.Join(notes, "; ")))
		}
		b.WriteString("</table></div></section>")
	}
	b.WriteString("<footer>Generated by <code>bbs team recap</code> from durable project state. Regenerate any time; the JSON snapshot stays the record.</footer></main></body></html>\n")
	return b.String()
}

func recapPhase(b *strings.Builder, p projectPhaseState) {
	esc := html.EscapeString
	fmt.Fprintf(b, `<article class=card><div class=row><h3>%s · %s</h3>%s</div>`, esc(p.ID), esc(p.Title), recapBadge(p.State))
	fmt.Fprintf(b, "<p class=meta>Release mode: %s · %d ticket(s): %s</p>", esc(p.Release), len(p.Children), esc(strings.Join(p.Children, ", ")))
	for _, r := range p.Releases {
		fmt.Fprintf(b, "<p>Release <code>%s</code> %s %s</p>", esc(orDefault(r.Tag, r.ID)), recapBadge(r.Verdict), esc(r.At))
	}
	if c := p.Candidate; c != nil {
		for _, r := range c.Repos {
			subject := gitOutIn(r.Canonical, "log", "-1", "--format=%s", r.Commit)
			fmt.Fprintf(b, "<p><code>%s</code> on <code>%s</code> in <code>%s</code> — %s</p>", esc(shortSHA(r.Commit)), esc(r.Base), esc(filepath.Base(r.Canonical)), esc(subject))
			recapDiff(b, r.Canonical, r.BaseHead, r.Commit)
		}
	}
	for _, n := range append(append([]string{}, p.Notes...), p.Problems...) {
		fmt.Fprintf(b, "<p class=note>%s</p>", esc(n))
	}
	b.WriteString("</article>")
}

// recapDiff lists the phase commit's files. Best effort: a pruned commit or
// missing checkout just omits the list.
func recapDiff(b *strings.Builder, dir, from, to string) {
	if from == "" || to == "" {
		return
	}
	out := gitOutIn(dir, "diff", "--numstat", from, to)
	if out == "" {
		return
	}
	lines := strings.Split(out, "\n")
	adds, dels := 0, 0
	var rows strings.Builder
	for _, l := range lines {
		f := strings.SplitN(l, "\t", 3)
		if len(f) != 3 {
			continue
		}
		a, _ := strconv.Atoi(f[0])
		d, _ := strconv.Atoi(f[1])
		adds, dels = adds+a, dels+d
		fmt.Fprintf(&rows, "<tr><td><code>%s</code></td><td class=add>+%s</td><td class=del>-%s</td></tr>", html.EscapeString(f[2]), f[0], f[1])
	}
	fmt.Fprintf(b, `<details><summary>%d files changed, <span class=add>+%d</span> <span class=del>-%d</span></summary><div class=scroll><table>%s</table></div></details>`, len(lines), adds, dels, rows.String())
}

func shortSHA(s string) string {
	if len(s) > 10 {
		return s[:10]
	}
	return s
}

func recapBadge(state string) string {
	class := "neutral"
	switch u := strings.ToUpper(state); {
	case strings.Contains(u, "FAIL"), strings.Contains(u, "BLOCK"), strings.Contains(u, "ROLLED"), strings.Contains(u, "STALE"):
		class = "bad"
	case u == "PASS", u == "DONE", u == "SUCCESS", u == "VERIFIED", u == "LANDED", u == "SEALED", u == "COVERED", u == "PROVEN", u == "DELIVERED", strings.HasPrefix(u, "RELEASED"):
		class = "good"
	}
	return fmt.Sprintf(`<span class="badge %s">%s</span>`, class, html.EscapeString(orDefault(state, "unknown")))
}

var (
	recapCode   = regexp.MustCompile("`([^`]+)`")
	recapBold   = regexp.MustCompile(`\*\*([^*]+)\*\*`)
	recapLink   = regexp.MustCompile(`\[([^\]]+)\]\(([^)\s]+)\)`)
	recapTblSep = regexp.MustCompile(`^\|?[\s:|-]+\|?$`)
)

func recapInline(s string) string {
	s = html.EscapeString(s)
	s = recapCode.ReplaceAllString(s, "<code>$1</code>")
	s = recapBold.ReplaceAllString(s, "<strong>$1</strong>")
	return recapLink.ReplaceAllString(s, `<a href="$2">$1</a>`)
}

// recapMarkdown renders the subset report.md uses: headings, lists, pipe
// tables, fenced code and paragraphs. Anything else reads as plain text.
func recapMarkdown(md string) string {
	var b strings.Builder
	lines := strings.Split(strings.ReplaceAll(md, "\r\n", "\n"), "\n")
	for i := 0; i < len(lines); i++ {
		l := strings.TrimRight(lines[i], " ")
		t := strings.TrimSpace(l)
		switch {
		case t == "":
		case strings.HasPrefix(t, "```"):
			b.WriteString("<pre>")
			for i++; i < len(lines) && !strings.HasPrefix(strings.TrimSpace(lines[i]), "```"); i++ {
				b.WriteString(html.EscapeString(lines[i]) + "\n")
			}
			b.WriteString("</pre>")
		case strings.HasPrefix(t, "#"):
			n := len(t) - len(strings.TrimLeft(t, "#"))
			if n > 4 {
				n = 4
			}
			fmt.Fprintf(&b, "<h%d>%s</h%d>", n+1, recapInline(strings.TrimSpace(t[n:])), n+1)
		case strings.HasPrefix(t, "|"):
			b.WriteString("<div class=scroll><table>")
			for row := 0; i < len(lines) && strings.HasPrefix(strings.TrimSpace(lines[i]), "|"); i, row = i+1, row+1 {
				r := strings.TrimSpace(lines[i])
				if recapTblSep.MatchString(r) {
					continue
				}
				cell := "td"
				if row == 0 {
					cell = "th"
				}
				b.WriteString("<tr>")
				for _, c := range strings.Split(strings.Trim(r, "|"), "|") {
					fmt.Fprintf(&b, "<%s>%s</%s>", cell, recapInline(strings.TrimSpace(c)), cell)
				}
				b.WriteString("</tr>")
			}
			i--
			b.WriteString("</table></div>")
		case strings.HasPrefix(t, "- "), strings.HasPrefix(t, "* "):
			b.WriteString("<ul>")
			for ; i < len(lines); i++ {
				r := strings.TrimSpace(lines[i])
				if !strings.HasPrefix(r, "- ") && !strings.HasPrefix(r, "* ") {
					break
				}
				fmt.Fprintf(&b, "<li>%s</li>", recapInline(r[2:]))
			}
			i--
			b.WriteString("</ul>")
		default:
			fmt.Fprintf(&b, "<p>%s</p>", recapInline(t))
		}
	}
	return b.String()
}

